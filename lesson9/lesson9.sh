#!/usr/bin/env bash
#
# bash_basics.sh — основи Bash на прикладах
# Курс «Кібербезпека з нуля», заняття №9
#
# Запуск:  chmod +x bash_basics.sh && ./bash_basics.sh
#
# Скрипт нічого не змінює в системі і не потребує sudo.
# Читайте код і одразу дивіться, що він надрукував.

set -euo pipefail
#  -e            вийти, якщо якась команда завершилась помилкою
#  -u            вийти, якщо звернулись до неіснуючої змінної (ловить опечатки)
#  -o pipefail   помилка всередині конвеєра не загубиться
#
# Ці три літери рятують від скрипта, який не спрацював, але зробив вигляд,
# що все добре. Пишіть їх на початку кожного скрипта.


echo "=============================================="
echo " 1. ЗМІННІ"
echo "=============================================="

# Пробілів навколо = бути НЕ повинно.
name="artem"
port=22

echo "Користувач: $name"
echo "Порт: $port"

# Подвійні лапки — змінна підставляється.
# Одинарні лапки — текст береться як є.
echo "У подвійних: $name"
echo 'У одинарних: $name'

# ГОЛОВНЕ ПРАВИЛО BASH: змінну завжди беремо в подвійні лапки.
file="my report.log"
echo "Правильно: '$file'"
# Без лапок bash розділить це на два слова — і команда отримає два аргументи
# замість одного. Саме на цьому ламається більшість скриптів.

echo
echo "=============================================="
echo " 2. ДІЇ З РЯДКАМИ"
echo "=============================================="

path="/var/log/auth.log"

echo "Шлях цілком:   $path"
echo "Довжина:       ${#path}"
echo "Тільки файл:   ${path##*/}"     # ## зрізає все до останнього /
echo "Тільки папка:  ${path%/*}"      # %  зрізає з кінця
echo "Без .log:      ${path%.log}"
echo "Заміна:        ${path/log/LOG}" # замінити перше входження

# Якщо змінної немає — підставити значення за замовчуванням:
echo "Типове:        ${nothing:-значення за замовчуванням}"

echo
echo "=============================================="
echo " 3. ЧИСЛА"
echo "=============================================="

a=17
b=5

echo "Сума:      $(( a + b ))"
echo "Різниця:   $(( a - b ))"
echo "Ділення:   $(( a / b ))    (тільки ціла частина!)"
echo "Залишок:   $(( a % b ))"

# Лічильник. Пишіть саме так, це найзрозуміліший спосіб:
counter=0
counter=$(( counter + 1 ))
counter=$(( counter + 1 ))
echo "Лічильник: $counter"

# Bash не вміє дробові числа. Якщо треба — кличемо awk:
echo "Дроби:     $(awk 'BEGIN { printf "%.2f", 17 / 5 }')"

echo
echo "=============================================="
echo " 4. УМОВИ"
echo "=============================================="

# [[ ]] — для рядків і файлів
# (( )) — для чисел

if (( port == 22 )); then
    echo "Порт 22 — це SSH"
fi

if [[ "$name" == "artem" ]]; then
    echo "Привіт, $name"
else
    echo "Я тебе не знаю"
fi

# Перевірки файлів:
#   -e існує   -f файл   -d папка   -r читається   -w пишеться   -x запускається
#   -z рядок порожній    -n рядок непорожній

if [[ -r /etc/hosts ]]; then
    echo "Файл /etc/hosts читається"
else
    echo "Файл /etc/hosts недоступний"
fi

if [[ -d /tmp ]]; then
    echo "Папка /tmp існує"
fi

echo
echo "=============================================="
echo " 5. CASE — КОЛИ ВАРІАНТІВ БАГАТО"
echo "=============================================="

# Замість довгого ланцюга if / elif / elif
system=$(uname -s)

case "$system" in
    Linux)
        echo "Це Linux (або WSL)"
        ;;
    Darwin)
        echo "Це macOS"
        ;;
    *)
        echo "Невідома система: $system"
        ;;
esac

echo
echo "=============================================="
echo " 6. ЦИКЛИ"
echo "=============================================="

echo "--- for по списку ---"
for service in ssh cron nginx; do
    echo "Перевіряю: $service"
done

echo "--- for по числах ---"
for i in 1 2 3; do
    echo "Крок $i"
done

echo "--- while з лічильником ---"
n=1
while (( n <= 3 )); do
    echo "n = $n"
    n=$(( n + 1 ))
done

echo
echo "=============================================="
echo " 7. МАСИВИ"
echo "=============================================="

ports=(22 80 443 3389)

echo "Усі порти:     ${ports[*]}"   # [*] — коли друкуємо одним рядком
echo "Скільки їх:    ${#ports[@]}"
echo "Перший:        ${ports[1]}"

# Додати елемент
ports+=(8080)
echo "Після додання: ${ports[*]}"

# А коли перебираємо в циклі — завжди "${масив[@]}" у лапках
echo "--- перебираємо масив ---"
for p in "${ports[@]}"; do
    echo "Порт $p"
done

echo
echo "=============================================="
echo " 8. ФУНКЦІЇ"
echo "=============================================="

# Аргументи всередині функції: $1, $2, ...
# local — змінна живе тільки всередині функції

check_port() {
    local number="$1"

    if (( number == 22 )); then
        echo "$number — SSH"
    elif (( number == 3389 )); then
        echo "$number — RDP, назовні не тримати!"
    else
        echo "$number — щось інше"
    fi
}

check_port 22
check_port 3389
check_port 8080

echo
echo "=============================================="
echo " 9. КОМАНДИ ВСЕРЕДИНІ СКРИПТА"
echo "=============================================="

# $( ) — виконати команду і підставити її вивід
today=$(date '+%Y-%m-%d')
echo "Сьогодні: $today"

user=$(whoami)
echo "Я працюю від імені: $user"

echo
echo "=============================================="
echo " 10. РОБОТА З ФАЙЛОМ І ЛОГАМИ"
echo "=============================================="

# Створимо невеликий тестовий лог у поточній папці.
# <<'EOF' — багаторядковий текст (heredoc).
cat > demo.log <<'EOF'
Aug  4 09:12:01 srv sshd: Failed password for root from 45.13.201.7
Aug  4 09:12:04 srv sshd: Failed password for admin from 45.13.201.7
Aug  4 09:13:44 srv sshd: Accepted password for artem from 10.0.0.5
Aug  4 09:14:02 srv sshd: Failed password for root from 193.42.11.9
Aug  4 09:15:31 srv sshd: Failed password for root from 45.13.201.7
EOF

echo "--- увесь файл ---"
cat demo.log

echo
echo "--- скільки рядків ---"
wc -l < demo.log

echo
echo "--- тільки невдалі входи (grep) ---"
grep "Failed password" demo.log

echo
echo "--- скільки їх (grep -c) ---"
grep -c "Failed password for root" demo.log

echo
echo "--- остання колонка кожного рядка (awk) ---"
# $1 — перша колонка, $2 — друга, $NF — остання
awk '{ print $NF }' demo.log

echo
echo "--- топ IP за кількістю невдалих входів ---"
# Конвеєр |: вивід однієї команди йде на вхід наступній.
# Читається зліва направо:
#   знайти рядки -> взяти останню колонку -> відсортувати
#   -> порахувати однакові -> відсортувати за кількістю
grep "Failed password" demo.log | awk '{ print $NF }' | sort | uniq -c | sort -rn

echo
echo "--- читаємо файл по рядку ---"
# -r обовʼязково, інакше bash зіпсує зворотні слеші
while read -r line; do
    echo "Рядок: $line"
done < demo.log

# Прибираємо за собою
rm -f demo.log

echo
echo "=============================================="
echo " 11. НАЙЧАСТІШІ ПОМИЛКИ"
echo "=============================================="

echo 'ПОГАНО:  cp $src $dst          ПРАВИЛЬНО:  cp "$src" "$dst"'
echo 'ПОГАНО:  while read line       ПРАВИЛЬНО:  while read -r line'
echo 'ПОГАНО:  for f in $(ls *.log)  ПРАВИЛЬНО:  for f in *.log'
echo 'ПОГАНО:  rm -rf $DIR/          ПРАВИЛЬНО:  rm -rf "${DIR:?}/"'
echo 'ПОГАНО:  cd $dir               ПРАВИЛЬНО:  cd "$dir" || exit'
echo
echo 'Усі ці помилки знаходить одна команда:  shellcheck script.sh'

echo
echo "=============================================="
echo " Готово. Тепер запустіть:  shellcheck bash_basics.sh"
echo "=============================================="