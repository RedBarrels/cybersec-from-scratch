#!/usr/bin/env bash
#
# scan_network.sh — хто живий у моїй підмережі
# Курс «Кібербезпека з нуля», заняття №10
#
# Перше питання будь-якого аудиту: скільки насправді пристроїв у мережі?
# Відповідь майже завжди більша за ту, що записана в інвентарі.
#
# Запуск:
#   ./scan_network.sh 192.168.1          # перебрати 192.168.1.1 – 192.168.1.254
#   ./scan_network.sh 192.168.1 1 50     # звузити діапазон
#
# ⚠ ЗАКОННІСТЬ. Скануйте лише мережі, якими володієте або на які маєте
# письмовий дозвіл. Сканування чужої мережі в Україні може кваліфікуватись
# за ст. 361 ККУ. У навчальних цілях: домашня мережа, лабораторна VM,
# або спеціальні полігони (scanme.nmap.org, HackTheBox, TryHackMe).
#
# ⚠ WSL. У WSL2 своя NAT-мережа. Скрипт побачить підмережу WSL, а не
# вашу домашню мережу Wi-Fi. Для реального сканування з Windows
# запускайте nmap у самому Windows, а не всередині WSL.

set -euo pipefail

PREFIX="${1:?Вкажіть перші три октети, напр.: $0 192.168.1}"
FIRST="${2:-1}"
LAST="${3:-254}"
MAX_JOBS=64          # скільки перевірок робити одночасно

# Проста перевірка вводу. Ніколи не довіряйте аргументу, який потім
# потрапить у команду: це вхідні двері для ін'єкції.
if [[ ! "$PREFIX" =~ ^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$ ]]; then
    echo "Некоректний префікс: $PREFIX (очікую щось на кшталт 192.168.1)" >&2
    exit 1
fi
#  =~ — порівняння з регулярним виразом, працює тільки всередині [[ ]]

if [[ -t 1 ]] && command -v tput >/dev/null 2>&1 && [[ "$(tput colors 2>/dev/null || echo 0)" -ge 8 ]]; then
    GREEN=$(tput setaf 2); BOLD=$(tput bold); DIM=$(tput dim); RESET=$(tput sgr0)
else
    GREEN=""; BOLD=""; DIM=""; RESET=""
fi

# --- Тимчасовий каталог для результатів -------------------------------------
#
# Перевірки йдуть паралельно, тому писати в одну змінну не можна:
# кожен фоновий процес має власну копію пам'яті. Домовляємось через файли.
#
# mktemp -d створює каталог з непередбачуваним іменем. Передбачуване
# ім'я на кшталт /tmp/scan.$$ — це TOCTOU-вразливість: локальний
# зловмисник встигає підкласти туди симлінк.
WORK_DIR=$(mktemp -d)
chmod 700 "$WORK_DIR"
trap 'rm -rf "$WORK_DIR"' EXIT      # прибрати за собою навіть при Ctrl+C

# --- Вибір методу перевірки --------------------------------------------------
#
# ICMP (ping) — найшвидший, але його часто фільтрують на файрволі:
# хост живий, а на ping не відповідає. Тому маємо запасний варіант —
# спроба відкрити TCP-з'єднання на типові порти.

PING_BIN=""
if command -v ping >/dev/null 2>&1; then
    PING_BIN="ping"
fi

# У Linux ключ -W задає таймаут у секундах, у macOS — у мілісекундах.
case "$(uname -s)" in
    Darwin*) PING_ARGS=(-c 1 -W 1000) ;;
    *)       PING_ARGS=(-c 1 -W 1) ;;
esac
#  PING_ARGS=(...) — масив. Далі підставляємо як "${PING_ARGS[@]}":
#  кожен елемент піде окремим аргументом, навіть якщо містить пробіл.

TCP_PORTS=(22 80 443 445 3389 8080)

tcp_probe() {
    # Повертає 0 (успіх), якщо хоч один порт відповів.
    local ip="$1" port
    for port in "${TCP_PORTS[@]}"; do
        # /dev/tcp/host/port — не файл, а спецможливість самого bash:
        # спроба відкрити TCP-з'єднання. У sh, dash і Git Bash її немає.
        if timeout 1 bash -c "exec 3<>/dev/tcp/$ip/$port" 2>/dev/null; then
            return 0
        fi
    done
    return 1
}

probe_host() {
    local ip="$1"
    if [[ -n "$PING_BIN" ]] && "$PING_BIN" "${PING_ARGS[@]}" "$ip" >/dev/null 2>&1; then
        echo "icmp" > "$WORK_DIR/$ip"
    elif tcp_probe "$ip"; then
        echo "tcp" > "$WORK_DIR/$ip"
    fi
    # Якщо хост не відповів — просто не створюємо файл.
}

# --- Сканування --------------------------------------------------------------

printf '%s\n' "${BOLD}=== Пошук живих хостів: ${PREFIX}.${FIRST}–${PREFIX}.${LAST} ===${RESET}"
if [[ -z "$PING_BIN" ]]; then
    printf '%sping не знайдено — використовую лише TCP-перевірку%s\n' "$DIM" "$RESET"
fi
printf '%s\n' "${DIM}Це займе кілька секунд...${RESET}"

started=$(date +%s)

for octet in $(seq "$FIRST" "$LAST"); do
    probe_host "${PREFIX}.${octet}" &
    #  & запускає перевірку у фоні, тому 254 адреси перевіряються
    #  не по черзі, а пачками.

    # Не запускаємо тисячу процесів одразу: чекаємо, поки їх стане менше.
    while (( $(jobs -rp | wc -l) >= MAX_JOBS )); do
        sleep 0.05
    done
done

wait        # дочекатись усіх фонових перевірок
elapsed=$(( $(date +%s) - started ))

# --- Результат ---------------------------------------------------------------

echo
# sort -t. -k4 -n — відсортувати IP по-людськи: роздільник «крапка»,
# сортувати за 4-м полем як за числом (інакше .10 стане б перед .2).
for file in "$WORK_DIR"/*; do
    [[ -e "$file" ]] || continue        # каталог порожній — нема чого показувати
    printf '%s %s\n' "$(basename "$file")" "$(cat "$file")"
done | sort -t. -k4 -n | while read -r ip method; do
    printf '  %s●%s %-16s %s(%s)%s\n' "$GREEN" "$RESET" "$ip" "$DIM" "$method" "$RESET"
done

# Порахувати хости всередині циклу вище не вийде: усе, що стоїть у конвеєрі,
# bash виконує в підоболонці, і зміна змінної туди не «протікає» назовні.
# Це класична пастка. Рахуємо файли окремою командою.
found=$(find "$WORK_DIR" -type f | wc -l | tr -d ' ')

echo
printf 'Живих хостів: %s%s%s   ·   час: %s с\n' "$BOLD" "$found" "$RESET" "$elapsed"
echo
printf '%sДалі:%s деталі по портах і сервісах — nmap:\n' "$BOLD" "$RESET"
printf '  nmap -sV -T4 %s.0/24\n' "$PREFIX"
printf '  nmap -sn %s.0/24        # тільки виявлення хостів\n' "$PREFIX"
